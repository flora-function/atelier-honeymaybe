// A Neon Function is bundled into one file on a read-only filesystem, so the admin
// page can't be served from disk. This inlines public/admin.* into src/admin-assets.js.
// Run `npm run build:admin` after editing anything in server/public/.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = { 'admin.html': 'text/html; charset=utf-8', 'admin.css': 'text/css; charset=utf-8', 'admin.js': 'text/javascript; charset=utf-8' };

const assets = Object.fromEntries(
  Object.entries(files).map(([name, type]) => [name, { type, body: fs.readFileSync(path.join(root, 'public', name), 'utf8') }])
);

fs.writeFileSync(
  path.join(root, 'src/admin-assets.js'),
  `// GENERATED by scripts/build-admin.js from public/ — do not edit by hand.\nexport default ${JSON.stringify(assets, null, 2)};\n`
);
console.log('wrote src/admin-assets.js');
